	/**
	 * 抓取任务日志
	 * <p>
	 *  任务日志目录
	 *  <br>/usr/migrationWebApp/joblog/{jobId}/{jobInsId}.log
	 *	<br>/usr/migrationWebApp/joblog/{jobname}/{jobinsname}.log
	 *	<br>
	 *	文件内容规则
	 *	<br>{tasked}:XXXXXXXXXXXXXXXXXXXXXXXXXXX
	 *	
	 * @param jobd
	 * @param jobInsId
	 * @param taskId
	 * @return
	 */
	public String fetchLog(String jobId, String jobInsId, String taskId){
		String html = "";
		String path = INIT.localFileRootDirectory + "/joblog/" + jobId +"/"+ jobInsId+".log";
		
		 /*
	     * 以行为单位读取文件，常用于读面向行的格式化文件
	     */
        File file = new File(path);
        if(!file.exists()){
        	return "没有相应的日志文件！";
        }
        BufferedReader reader = null;
        try {
            reader = new BufferedReader(new FileReader(file));
            String tempString = null;
            int line = 1;
            // 一次读入一行，直到读入null为文件结束
            while ((tempString = reader.readLine()) != null) {
                // 显示行号
                System.out.println("line " + line + ": " + tempString);
                if( tempString.startsWith( taskId+":" ) ){
                	html += tempString.substring( taskId.length()+1 ) + "<br/>";
                }
                line++;
            }
            reader.close();
        } catch (IOException e) {
            e.printStackTrace();
            throw new BusinessException("读文件时出错！");
        } finally {
            if (reader != null) {
                try {
                    reader.close();
                } catch (IOException e1) {
                	throw new BusinessException("关闭文件流时出错！");
                }
            }
        }
        
		return html;
	}
	
